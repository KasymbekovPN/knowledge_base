// Versioning интерфейсов: как добавить новую возможность, не трогая
// layout уже опубликованного интерфейса и не ломая уже собранных
// потребителей ("старые бинарники" тут смоделированы как отдельный класс,
// написанный ПРОТИВ старого интерфейса и не подозревающий о новом).

#include <iostream>
#include <format>

// ---------------------------------------------------------------------------
// V1 - опубликованный интерфейс. У него уже есть внешние реализации
// (представим - в закрытых бинарниках, которые мы не можем пересобрать).
// Его vtable-layout НИКОГДА больше не меняется - ни один метод не
// добавляется, не удаляется, не переставляется.
// ---------------------------------------------------------------------------
class IRenderV1 {
public:
    virtual ~IRenderV1() = default;
    virtual void drawPixel(int x, int y) = 0;
};

// ---------------------------------------------------------------------------
// V2 - НОВЫЙ интерфейс, расширяющий V1 через наследование, а не изменяющий
// его. Существующие реализации V1 эту иерархию вообще не видят - для них
// ничего не поменялось ни на уровне исходников, ни на уровне ABI.
// ---------------------------------------------------------------------------
class IRenderV2: public IRenderV1 {
public:
    virtual void drawLine(int x1, int y1, int x2, int y2) = 0;
};

// ---------------------------------------------------------------------------
// "Старый" плагин - собран когда-то давно, знает только про V1.
// Пересобирать/трогать его исходники мы не можем и не должны.
// ---------------------------------------------------------------------------
class OldSoftwareRenderer: public IRenderV1 {
public:
    void drawPixel(int x, int y) override {
        std::cout << std::format("  [software] pixel({}, {})\n", x, y);
    }
};

// ---------------------------------------------------------------------------
// "Новый" плагин - собран сегодня, реализует расширенный V2.
// ---------------------------------------------------------------------------
class NewGpuRenderer: public IRenderV2 {
public:
    void drawPixel(int x, int y) override {
        std::cout << std::format("  [gpu] pixel({}, {})\n", x, y);
    }
    void drawLine(int x1, int y1, int x2, int y2) override {
        std::cout << std::format("  [gpu] line ({}, {}) -> ({}, {})", x1, y1, x2, y2);
    }
};

// ---------------------------------------------------------------------------
// Host работает с базовым IRendererV1& - гарантированно совместим с ЛЮБОЙ
// реализацией, старой или новой. Дополнительные возможности V2
// запрашиваются через dynamic_cast как необязательный "capability query" -
// если объект реально реализует V2, используем более эффективный путь;
// если нет (старый плагин) - работаем через гарантированный минимум V1.
// ---------------------------------------------------------------------------
void render(IRenderV1& renderer) {
    renderer.drawPixel(1, 1);

    if (auto* it = dynamic_cast<IRenderV2*>(&renderer)) {
        it->drawLine(0, 0, 10, 10);
    } else {
        std::cout << "  drawLine is not support\n";
    }
}

int main() {
    OldSoftwareRenderer oldRenderer;
    NewGpuRenderer newRenderer;

    render(oldRenderer);
    render(newRenderer);

    return 0;
}
